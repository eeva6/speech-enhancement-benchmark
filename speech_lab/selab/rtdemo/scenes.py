def build_libricss(cond="OV40", pick=None, sid="libricss_ov40"):
    from .. import libricss as LC
    meta5 = json.load(open(MIX / "r5" / "meta.json"))
    cands = [m for m in meta5 if m["cond"] == cond and 4 <= m["dur"] <= 12 and m["ovl"] > 0.2]
    m = cands[0] if pick is None else [c for c in cands if c["id"] == pick][0]
    d = [dd for c, s, dd in LC.sessions((cond,), (m["session"],))][0]
    info = LC.read_info(d)
    u = [v for v in info if v["uid"] == m["uid"]][0]
    A = m["clock"]
    lag = np.polyval(A, (u["start"] + u["end"]) / 2)
    t0 = max(u["start"] - 3.0, 0.0)
    a = int(t0 * FS + lag); n = int(DUR * FS)
    y, _ = sf.read(d + "/record/raw_recording.wav", dtype="float32", start=a, stop=a + n)
    x = y.T
    # talker directions: system-ID az of every r5 item in this recording, keyed by loudspeaker channel
    same = [q for q in meta5 if q["cond"] == cond and q["session"] == m["session"]]
    ch_az = {}
    for q in same:
        ch_az.setdefault(q["ch"], q["az_sysid"])
    xdry, _ = sf.read(d + "/clean/each_spk.wav", dtype="float32", start=int(t0 * FS), stop=int(t0 * FS) + n)
    look = float(m["az_sysid"])
    talkers = []
    for v in info:
        if v["end"] < t0 or v["start"] > t0 + DUR:
            continue
        seg = xdry[max(int((v["start"] - t0) * FS), 0): int((v["end"] - t0) * FS)]
        if len(seg) == 0:
            continue
        ch = int(np.argmax((seg ** 2).sum(0)))
        az = ch_az.get(ch)
        rel = None if az is None else float(((az - look) + 180) % 360 - 180)
        talkers.append(dict(name=f"spk {v['spk']} (loudspeaker {ch})", az=rel, target=(v["uid"] == m["uid"]),
                            acts=[(max(v["start"] - t0, 0), min(v["end"] - t0, DUR))]))
    meta = dict(id=sid, title=f"Real LibriCSS meeting room ({cond}), 7-mic table array",
                kind="libricss", array="libricss7", xy=LC.MIC_XY.tolist(), front=0, head_az_array=look,
                look_az_array=look, scene_type="meeting", r5_item=m["id"], session=m["session"], t0_playback=t0,
                talkers=talkers,
                licence="LibriCSS (CC BY 4.0, Chen et al. 2020) re-recording of LibriSpeech (CC BY 4.0)",
                external_ok=True,
                notes="table array, not glasses: 'head direction' = ORACLE look direction (system-ID azimuth of the "
                      "target loudspeaker), as if the wearer faced the target; talkers without an r5 system-ID "
                      "azimuth are shown without a direction")
    _write(sid, x, meta)


