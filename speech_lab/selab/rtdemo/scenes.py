def _write(sid, x, meta, comps=None):
    d = OUTD / sid; d.mkdir(parents=True, exist_ok=True)
    x = np.asarray(x, np.float32)
    sf.write(d / "mc.wav", x.T, FS, subtype="FLOAT")
    for k, v in (comps or {}).items():
        sf.write(d / f"comp_{k}.wav", np.asarray(v, np.float32), FS, subtype="FLOAT")
    meta.update(n=int(x.shape[1]), channels=int(x.shape[0]), fs=FS)
    json.dump(meta, open(d / "scene.json", "w"), indent=1)
    print(sid, x.shape, meta.get("licence"), flush=True)


# ------------------------------------------------------------------------------------------------ simulated
def _ls_items():
    from ..mixtures import librispeech_index
    by = {}
    for it in librispeech_index():
        by.setdefault(it["spk"], []).append(it)
    return by


def _talk(paths, n, rng, gap=(0.3, 0.8), start=0.3):
    y = np.zeros(n, np.float32); t = int(start * FS); acts = []
    for p in paths:
        s = load(p)
        if t >= n:
            break
        seg = s[: n - t]; y[t:t + len(seg)] += seg; acts.append((t / FS, (t + len(seg)) / FS))
        t += len(seg) + int(rng.uniform(*gap) * FS)
    return y, acts


def _lin4_room(dims, rt60, c):
    import pyroomacoustics as pra
    if rt60 is None:      # near-free-field 'street': highly absorbing walls/ceiling, few reflections
        e_abs, mo = 0.9, 3
    else:
        e_abs, mo = pra.inverse_sabine(rt60, dims)
    room = pra.ShoeBox(dims, fs=FS, materials=pra.Material(e_abs), max_order=min(mo, 30))
    xs = [(-1.5 + i) * 0.04 for i in range(4)]
    room.add_microphone_array(np.stack([c + np.array([x, 0, 0]) for x in xs], 1))
    return room, xs


def _spat(room, srcs, pos, n):
    for s, p in zip(srcs, pos):
        room.add_source(p, signal=s)
    room.compute_rir()
    from scipy.signal import fftconvolve
    out = []
    for k, s in enumerate(srcs):
        out.append(np.stack([fftconvolve(s, room.rir[m][k])[:n] for m in range(4)]))
    out = [np.pad(o, ((0, 0), (0, max(0, n - o.shape[1])))) for o in out]
    return out


def _pos(c, az, d, dz=0.0):
    a = np.deg2rad(az)
    return c + np.array([d * np.cos(a), d * np.sin(a), dz])


def build_sim_street(seed=11):
    rng = np.random.default_rng(seed); n = int(DUR * FS)
    by = _ls_items(); spk = sorted(by)[3]
    paths = sorted(it["path"] for it in by[spk])[:8]
    tgt, acts = _talk(paths, n, rng)
    # synthetic car pass-by (ear signal "d" of the lab's ANC simulation, 44.1 kHz, 10 s), resampled to 16 kHz
    z = np.load(f"{ANC_LAB}/results/anc_passby/runs/c1_glasses_4mic7_causal.npz")
    car = resample_poly(z["d"].astype(np.float64), 160, 441).astype(np.float32)
    car /= np.sqrt(np.mean(car ** 2))
    c1 = np.zeros(n, np.float32); c1[: min(n, len(car))] = car[:n]
    c2 = np.zeros(n, np.float32); o = int(6.5 * FS); L = min(n - o, len(car)); c2[o:o + L] = car[:L]
    bed = np.cumsum(rng.standard_normal(n)).astype(np.float32); bed -= np.convolve(bed, np.ones(400) / 400, "same")
    bed /= np.sqrt(np.mean(bed ** 2)) * 4
    dims = np.array([40.0, 30.0, 12.0]); c = np.array([20.0, 12.0, 1.6])
    room, xs = _lin4_room(dims, None, c)
    head_az = 90.0     # array broadside (+y) = wearer forward
    # road on the wearer's RIGHT (array az 0 = +x = wearer's right; head = array az 90).  A first version put the
    # road behind (array az -60/-120/-90): that is the mirror lobe of a linear array, so no beamformer can help.
    imgs = _spat(room, [tgt, c1, c2, bed], [_pos(c, 90, 1.5), _pos(c, -20, 9, -1.2), _pos(c, 20, 9, -1.2),
                                           _pos(c, 0, 12, -1.2)], n)
    t_img = imgs[0]; noise = imgs[1] + imgs[2] + imgs[3]
    snr = 0.0
    noise *= np.sqrt(np.mean(t_img[1] ** 2) / np.mean(noise[1] ** 2)) / 10 ** (snr / 20)
    x = t_img + noise; g = 0.5 / np.max(np.abs(x)); x *= g
    meta = dict(id="sim_street", title="Simulated street: talker ahead, two synthetic car pass-bys",
                kind="sim", array="lin4", xy=[[xx, 0.0] for xx in xs], front=1, head_az_array=head_az,
                look_az_array=head_az, scene_type="traffic", snr_db_front=snr,
                talkers=[dict(name="target (ahead)", az=0.0, acts=acts, target=True),
                         dict(name="car 1 (road on the right)", az=-110.0, acts=[(0, 10.0)], target=False),
                         dict(name="car 2 (road on the right)", az=-70.0, acts=[(6.5, 16.0)], target=False)],
                licence="LibriSpeech dev-clean (CC BY 4.0) speech; synthetic car noise generated by the lab's own "
                        "ANC pass-by simulation; pyroomacoustics room simulation",
                external_ok=True, ls_speaker=spk, notes="near-anechoic 40x30x12 m box (wall energy absorption 0.9, image order 3) as a street stand-in")
    _write("sim_street", x, meta, dict(target=t_img[1] * g, noise=noise[1] * g))


def build_sim_restaurant(seed=12):
    rng = np.random.default_rng(seed); n = int(DUR * FS)
    by = _ls_items(); spks = sorted(by)
    tgt, acts = _talk(sorted(it["path"] for it in by[spks[5]])[:8], n, rng)
    comp, acts_c = _talk(sorted(it["path"] for it in by[spks[9]])[:8], n, rng, gap=(1.5, 3.0), start=2.0)
    bab = []
    for s in spks[12:18]:
        p = sorted(it["path"] for it in by[s])
        b, _ = _talk(p[:10], n, rng, gap=(0.05, 0.2), start=float(rng.uniform(0, 1)))
        bab.append(b / (np.sqrt(np.mean(b ** 2)) + 1e-9))
    dims = np.array([9.0, 7.0, 3.0]); c = np.array([4.0, 3.0, 1.2])
    room, xs = _lin4_room(dims, 0.5, c)
    head_az = 90.0
    pos = [_pos(c, 80, 1.2), _pos(c, 150, 1.5)] + [_pos(c, a, float(rng.uniform(2.0, 3.2)), 0.2)
                                                 for a in np.linspace(0, 360, 7)[:-1] + 25]
    imgs = _spat(room, [tgt, comp] + bab, pos, n)
    t_img, c_img = imgs[0], imgs[1]; b_img = sum(imgs[2:])
    pt = np.mean(t_img[1] ** 2)
    c_img *= np.sqrt(pt / np.mean(c_img[1] ** 2)) / 10 ** (2 / 20)      # competing talker 2 dB below target
    b_img *= np.sqrt(pt / np.mean(b_img[1] ** 2)) / 10 ** (3 / 20)      # babble 3 dB below target
    x = t_img + c_img + b_img; g = 0.5 / np.max(np.abs(x)); x *= g
    meta = dict(id="sim_restaurant", title="Simulated restaurant: companion ahead, talker on the left, babble",
                kind="sim", array="lin4", xy=[[xx, 0.0] for xx in xs], front=1, head_az_array=head_az,
                look_az_array=head_az, scene_type="restaurant",
                talkers=[dict(name="companion (target, 10 deg right)", az=-10.0, acts=acts, target=True),
                         dict(name="other talker (60 deg left)", az=60.0, acts=acts_c, target=False)],
                licence="LibriSpeech dev-clean (CC BY 4.0) speech; pyroomacoustics room simulation",
                external_ok=True, notes="RT60 0.5 s 9x7x3 m room; target-to-competitor 2 dB, target-to-babble 3 dB at the front mic")
    # 'target' comp = companion(s) (talkers the listener wants), 'noise' = babble + other talker
    _write("sim_restaurant", x, meta, dict(target=t_img[1] * g, noise=(c_img[1] + b_img[1]) * g))


