"""Build the demo scenes (16 s each) into listening/rtdemo/scenes/<id>/.

Per scene: mc.wav (M ch, float32, 16 kHz) = the array input fed block by block to the streaming engine;
optional comp_target.wav / comp_noise.wav (front-mic images of target talker(s) and noise, simulated scenes only,
used ONLY by the SIMULATED noise-cut track); scene.json (array, geometry, front mic, head direction, talker
directions and activity for the display, licence, external-OK flag).

Scenes
  sim_street      4-mic linear (4 cm), pyroomacoustics near-anechoic "street" box; target LibriSpeech talker ahead
                  1.5 m; noise = two SYNTHETIC car pass-bys (the ear signal of the lab's ANC pass-by simulation,
                  generated by our own code) from the road side + a low synthetic bed.  Licence-clean.
  sim_restaurant  4-mic linear (4 cm), RT60 0.5 s room; target ahead (10 deg off the head axis) 1.2 m, competing
                  talker 60 deg left 1.5 m, 6-talker LibriSpeech babble.  Licence-clean (LibriSpeech CC BY 4.0).
  libricss_ov40   REAL LibriCSS 7-mic circle recording (OV40, 40% overlap), 16 s around an r5 target utterance.
                  CC BY 4.0 (LibriCSS / LibriSpeech).  Look direction = the target loudspeaker's system-ID azimuth.
  easycom_s10/s11 REAL EasyCom glasses recordings (6 ch: frame mics ch1-4 + in-ear ch5-6). CC BY-NC 4.0,
                  research only: INTERNAL LISTENING ONLY.
Azimuths in scene.json/talkers are HEAD-RELATIVE (0 = straight ahead, + = left), for the display.
"""
