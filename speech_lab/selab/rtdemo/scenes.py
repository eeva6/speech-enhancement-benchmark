def easycom_pick(sess, nbest=1, wearer=2):
    best = []
    for seg in E.segs(sess):
        ut = E.transcripts(sess, seg)
        doa = np.load(E.CACHE / f"Session_{sess}" / f"{seg}.doa.npz")
        if not (E.CACHE / f"Session_{sess}" / f"{seg}.wav").exists():
            continue
        for t0 in np.arange(2.0, 60 - DUR - 1, 2.0):
            grid = np.arange(t0, t0 + DUR, 0.1)
            act = {}
            for v in ut:
                if v["pid"] == wearer:
                    continue
                act.setdefault(v["pid"], np.zeros(len(grid), bool))
                act[v["pid"]] |= (grid >= v["start"]) & (grid < v["end"])
            if not act:
                continue
            A = np.stack(list(act.values()))
            cov = A.any(0).mean(); ovl = (A.sum(0) >= 2).mean(); ntalk = int((A.any(1)).sum())
            wear = np.zeros(len(grid), bool)
            for v in ut:
                if v["pid"] == wearer:
                    wear |= (grid >= v["start"]) & (grid < v["end"])
            k = (grid * 20).astype(int)
            valid = float(np.mean(doa["wearer_valid"][np.clip(k, 0, len(doa["wearer_valid"]) - 1)]))
            if valid < 0.95:
                continue
            score = cov + 0.5 * ovl + 0.1 * min(ntalk, 3) - 0.5 * wear.mean()
            best.append((score, seg, float(t0), cov, ovl, ntalk, float(wear.mean())))
    best.sort(reverse=True)
    return best[:nbest]


def build_easycom(sess, sid):
    sc, seg, t0, cov, ovl, ntalk, wear = easycom_pick(sess)[0]
    x = E.load_array16(sess, seg)
    a = int(t0 * FS); n = int(DUR * FS); x = x[:, a:a + n]
    doa = np.load(E.CACHE / f"Session_{sess}" / f"{seg}.doa.npz")
    ut = E.transcripts(sess, seg)
    k0 = int(round(t0 * 20)); K = int(DUR * 20)
    talkers = []
    for pid in doa["ids"]:
        pid = int(pid)
        az = doa[f"az_{pid}"][k0:k0 + K]
        acts = [(max(v["start"] - t0, 0), min(v["end"] - t0, DUR)) for v in ut
                if v["pid"] == pid and v["end"] > t0 and v["start"] < t0 + DUR]
        talkers.append(dict(name=f"participant {pid}", az_series=[None if not np.isfinite(q) else round(float(q), 1) for q in az],
                            az_series_fps=20.0, acts=acts, target=False))
    wa = [(max(v["start"] - t0, 0), min(v["end"] - t0, DUR)) for v in ut if v["pid"] == 2 and v["end"] > t0 and v["start"] < t0 + DUR]
    meta = dict(id=sid, title=f"Real EasyCom glasses recording, session {sess} (restaurant-noise conversation)",
                kind="easycom", array="easycom", front=1, ear=[4, 5], head_az_array=0.0, look_az_array=0.0,
                scene_type="restaurant", session=sess, segment=seg, t0=t0,
                pick=dict(score=round(sc, 3), talker_coverage=round(cov, 3), overlap=round(ovl, 3),
                          n_talkers=ntalk, wearer_speech=round(wear, 3)),
                talkers=talkers, wearer_acts=wa,
                licence="EasyCom (Meta, CC BY-NC 4.0, research only)", external_ok=False,
                notes="6 channels: frame mics ch1-4 (used by the beamformers) + in-ear mics ch5-6. INTERNAL ONLY.")
    _write(sid, x, meta)


def main():
    import sys
    which = sys.argv[1:] or ["sim_street", "sim_restaurant", "libricss_ov40", "easycom_s10", "easycom_s11"]
    for w in which:
        if (OUTD / w / "scene.json").exists():
            print("exists", w); continue
        {"sim_street": build_sim_street, "sim_restaurant": build_sim_restaurant,
         "libricss_ov40": lambda: build_libricss("OV40"),
         "easycom_s10": lambda: build_easycom(10, "easycom_s10"),
         "easycom_s11": lambda: build_easycom(11, "easycom_s11")}[w]()


if __name__ == "__main__":
    main()
