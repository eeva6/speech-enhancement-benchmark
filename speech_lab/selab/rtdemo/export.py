"""Export before/after clip pairs (16 s) per scene + clip list + a zip of the licence-clean clips only.

listening/rtdemo/clips/external_ok/<scene>/      licence-clean scenes (LibriSpeech/LibriCSS CC BY 4.0, synthetic)
listening/rtdemo/clips/INTERNAL_ONLY_easycom/<scene>/   EasyCom (CC BY-NC 4.0, research only): never share
  before_raw.wav / after_hs_sd4.wav                 engine output as rendered (raw level, 16-bit)
  before_raw_LM.wav / after_hs_sd4_LM.wav           loudness-matched pair: both at -23 dB gated RMS (BS.1770 gating,
                                                    no K-weighting), same gain cap so neither peaks above -1 dBFS
  extra_hyb_sd4(_LM).wav, extra_trk_sd4(_LM).wav    other steering modes
  SIMULATED_noise_cut.wav                           the SIMULATED noise-cut track at its own (lower) level, not LM
results/rtdemo/clip_list.csv / clip_list.md
listening/rtdemo/clips_external_ok.zip              licence-clean clips only + ATTRIBUTION.txt (no EasyCom audio)
"""
import csv, json, zipfile
import numpy as np
import soundfile as sf
from ..common import ROOT, FS
from .render import REN, SCENES, gated_rms_db
from .scenes import OUTD

CL = ROOT / "listening" / "rtdemo" / "clips"
TARGET_DB = -23.0
PAIRS = [("before_raw", "raw"), ("after_hs_sd4", "hs_sd4"), ("extra_hyb_sd4", "hyb_sd4"), ("extra_trk_sd4", "trk_sd4")]


def main():
    rows = []
    for sid in SCENES:
        meta = json.load(open(OUTD / sid / "scene.json"))
        ext = bool(meta["external_ok"])
        d = CL / ("external_ok" if ext else "INTERNAL_ONLY_easycom") / sid; d.mkdir(parents=True, exist_ok=True)
        ys = {nm: np.load(REN / sid / f"{m}.f32.npy").astype(np.float64) for nm, m in PAIRS}
        g = {nm: 10 ** ((TARGET_DB - gated_rms_db(y)) / 20) for nm, y in ys.items()}
        pk = max(np.max(np.abs(y * g[nm])) for nm, y in ys.items())
        cap = min(1.0, 10 ** (-1 / 20) / pk)                  # common cap keeps the pair's levels equal
        for nm, y in ys.items():
            sf.write(d / f"{nm}.wav", np.clip(y, -1, 1), FS, subtype="PCM_16")
            sf.write(d / f"{nm}_LM.wav", np.clip(y * g[nm] * cap, -1, 1), FS, subtype="PCM_16")
        sim = np.load(REN / sid / "anc_sim.f32.npy").astype(np.float64)
        sf.write(d / "SIMULATED_noise_cut.wav", np.clip(sim, -1, 1), FS, subtype="PCM_16")
        lic = ("OK for outside listeners (attribution: " + meta["licence"] + ")") if ext else \
              "INTERNAL ONLY. EasyCom is CC BY-NC 4.0, research use only. Do not play to or share with outside people."
        (d / "LICENCE.txt").write_text(f"{meta['title']}\n{lic}\n\n{meta.get('notes', '')}\n"
                                       "Processed recorded audio (causal 2 ms block engine). Not at-ear sound; no open-ear "
                                       "leakage, feedback or real ANC. SIMULATED_noise_cut.wav is a simulation.\n")
        for nm, m in PAIRS + [("SIMULATED_noise_cut", "anc_sim")]:
            rows.append(dict(scene=sid, file=str((d / f"{nm}.wav").relative_to(ROOT)), mode=m,
                             loudness_matched_copy=("" if m == "anc_sim" else str((d / f"{nm}_LM.wav").relative_to(ROOT))),
                             duration_s=round(meta["n"] / FS, 2), source=meta["kind"], licence=meta["licence"],
                             external_ok="yes" if ext else "NO (internal only)",
                             level_db_gated_rms=round(gated_rms_db(sim if m == "anc_sim" else ys[nm]), 2)))
    out = ROOT / "results" / "rtdemo"
    with open(out / "clip_list.csv", "w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=list(rows[0])); w.writeheader(); w.writerows(rows)
    md = ["# Clip list (16 s each)", "", "Loudness-matched (`_LM`) copies: -23 dB gated RMS, BS.1770 gating, no K-weighting; "
          "a common gain cap keeps both clips of a scene below -1 dBFS.", "",
          "| scene | file | mode | external OK | licence |", "|---|---|---|---|---|"]
    for r in rows:
        md.append(f"| {r['scene']} | `{r['file']}` | {r['mode']} | {r['external_ok']} | {r['licence']} |")
    (out / "clip_list.md").write_text("\n".join(md) + "\n")
    zp = ROOT / "listening" / "rtdemo" / "clips_external_ok.zip"
    with zipfile.ZipFile(zp, "w", zipfile.ZIP_DEFLATED) as z:
        for p in sorted((CL / "external_ok").rglob("*")):
            if p.is_file():
                assert "easycom" not in str(p).lower()
                z.write(p, p.relative_to(CL))
        z.writestr("ATTRIBUTION.txt",
                   "LibriSpeech (Panayotov et al. 2015), CC BY 4.0. LibriCSS (Chen et al. 2020), CC BY 4.0.\n"
                   "Synthetic car pass-by noise and room simulations generated by the lab's own code (pyroomacoustics).\n"
                   "Processed recorded audio only: not at-ear sound, no open-ear leakage, feedback or real ANC.\n"
                   "Files named SIMULATED_* apply simulated ANC attenuation spectra; they are not real ANC.\n")
    print("clips:", len(rows), "zip:", zp)


if __name__ == "__main__":
    main()
