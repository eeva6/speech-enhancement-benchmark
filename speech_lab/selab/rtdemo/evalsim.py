"""Sanity metric for the simulated scenes: exact SNR change of each mode, from separately processed target and
noise images (the filters are linear for a given steering sequence; the trk/hyb steering is replayed from the
mixture render, so it is exactly what the mixture saw).  Also A-weighted level changes of the SIMULATED track.

The images are regenerated by re-running the (seeded) scene builders in memory; the script asserts that
target + noise reproduces the saved mc.wav before using them.   -> results/rtdemo/sim_snr.json
"""
import json
import numpy as np
from ..common import ROOT, FS
from .. import r6
from . import scenes as S
from .engine import B, sd4_wng, load_scene
from .anc_sim import filters as anc_filters, dba_change
from scipy.signal import lfilter


def capture(builder):
    got = {}
    orig_write, orig_spat = S._write, S._spat

    def spat(room, srcs, pos, n):
        out = orig_spat(room, srcs, pos, n); got["imgs"] = [o.copy() for o in out]; return out

    def write(sid, x, meta, comps=None):
        got["x"] = np.asarray(x, np.float32); got["meta"] = meta
    S._write, S._spat = write, spat
    try:
        builder()
    finally:
        S._write, S._spat = orig_write, orig_spat
    return got


def run_filter(name, xy, x, steer_az, wng):
    p = r6.STFTBF(np.asarray(xy), win_ms=4, kind="sd", wng_db=wng) if name == "sd4" else r6.DSTime(np.asarray(xy))
    y = np.zeros(x.shape[1] // B * B)
    for k, i in enumerate(range(0, len(y), B)):
        y[i:i + B] = p.process_hop(x[:, i:i + B], float(steer_az[k]), 1) if name == "sd4" else p.process_hop(x[:, i:i + B], float(steer_az[k]))
    return y


def snr(t, n):
    return float(10 * np.log10(np.sum(t ** 2) / np.sum(n ** 2)))


def main():
    res = {}
    for sid, builder in (("sim_street", S.build_sim_street), ("sim_restaurant", S.build_sim_restaurant)):
        g = capture(builder); meta = g["meta"]
        saved_meta, xs, comps = load_scene(sid)
        assert np.allclose(g["x"], xs.astype(np.float32), atol=1e-6), "regenerated mixture differs from saved scene"
        imgs = g["imgs"]
        # exact components in saved scale: target = scaled t_img (fit from comp_target), noise = mixture - target
        t_img = imgs[0]
        a = float(np.dot(comps["target"], t_img[1]) / np.dot(t_img[1], t_img[1]))
        T = a * t_img; N = xs - T
        assert np.allclose(T[1], comps["target"], atol=1e-5)
        n = xs.shape[1] // B
        st = json.load(open(ROOT / "listening" / "rtdemo" / "render" / sid / "steer.json"))
        head = float(saved_meta["head_az_array"])
        tt = (np.arange(n) + 1) * B / FS
        def steer_series(key):
            idx = np.searchsorted(np.array(st["t"]), tt + 1e-9, side="right") - 1
            v = np.array(st[key]) + head if key else None
            if key == "trk":
                out = np.where(idx >= 0, v[np.clip(idx, 0, None)], 0.0)
            else:
                out = np.where(idx >= 0, v[np.clip(idx, 0, None)], head)
            return out
        R = dict(front_snr_db=snr(T[1], N[1]))
        for mode, filt, az in (("hs_ds", "ds", np.full(n, head)), ("hs_sd4", "sd4", np.full(n, head)),
                               ("trk_sd4", "sd4", steer_series("trk")), ("hyb_sd4", "sd4", steer_series("hyb"))):
            w = sd4_wng(saved_meta)
            yt = run_filter(filt, saved_meta["xy"], T, az, w); yn = run_filter(filt, saved_meta["xy"], N, az, w)
            R[mode] = dict(R.get(mode, {}), wng_db=w)
            R[mode].update(snr_db=snr(yt, yn), snr_gain_db=snr(yt, yn) - R["front_snr_db"])
        F, _ = anc_filters()
        nk = "traffic" if saved_meta["scene_type"] == "traffic" else "babble"
        at = lfilter(F["companion"], 1, comps["target"]); an = lfilter(F[nk], 1, comps["noise"])
        R["anc_sim"] = dict(snr_db=snr(at, an), snr_gain_db=snr(at, an) - snr(comps["target"], comps["noise"]),
                            talker_dBA_change=dba_change(comps["target"], at), noise_dBA_change=dba_change(comps["noise"], an),
                            noise_curve=nk)
        res[sid] = R
        print(sid, json.dumps(R), flush=True)
    json.dump(res, open(ROOT / "results" / "rtdemo" / "sim_snr.json", "w"), indent=1)


if __name__ == "__main__":
    main()
