def latency_of(m):
    if m in ("noisy",):
        return 0.0
    if m == "ds_est":
        return 32.0
    if m.startswith("mvdr_online"):
        return 32.0
    f = m.split("__")[0].rsplit("_", 1)[0]
    return r6.LATENCY_MS.get(f, np.nan)


def brittleness(w, ids, methods):
    rows = []
    for me in methods:
        s = w[(w.method == me) & w.id.isin(ids)].set_index("id")
        b = w[(w.method == "noisy") & w.id.isin(ids)].set_index("id")
        j = s.index.intersection(b.index)
        if not len(j):
            continue
        d = s.word_correct[j] - b.word_correct[j]
        rows.append(dict(method=me, label=label(me), n=len(j), catastrophic_frac=float((s.word_correct[j] < 0.3).mean()),
                         median_d=float(d.median()), n_better=int((d > 0.01).sum()), n_worse=int((d < -0.01).sum()),
                         n_same=int((d.abs() <= 0.01).sum())))
    return pd.DataFrame(rows)


def sim_vs_real(wr, ws, ids, methods, rng):
    rows = []
    for me in methods:
        dd = []
        for w in (wr, ws):
            a = w[(w.method == me) & w.id.isin(ids)].set_index("id").word_correct
            b = w[(w.method == "noisy") & w.id.isin(ids)].set_index("id").word_correct
            dd.append(a - b)
        j = dd[0].dropna().index.intersection(dd[1].dropna().index)
        if not len(j):
            continue
        df = pd.DataFrame(dict(dr=dd[0][j].values, ds=dd[1][j].values, cl=[cluster_of(i) for i in j]))
        df["diff"] = df.dr - df.ds
        e, lo, hi = boot(df, "diff", rng)
        rows.append(dict(method=me, label=label(me), n=len(j), d_real=df.dr.mean(), d_sim=df.ds.mean(), diff=e, lo=lo, hi=hi))
    return pd.DataFrame(rows)


def obj_table(tag, ids, methods, rng):
    p6 = R6 / f"metrics_{tag}.csv"; p5 = RES / "r5" / f"metrics_{tag}.csv"
    mt = pd.concat([pd.read_csv(p) for p in (p5, p6) if p.exists()]).drop_duplicates(["method", "id"], keep="last")
    mt = mt[mt.id.isin(ids)]
    rows = []
    for me in methods:
        r = dict(method=me, label=label(me))
        for col in ("si_sdr", "estoi"):
            a = mt[mt.method == me].set_index("id")[col]; b = mt[mt.method == "noisy"].set_index("id")[col]
            j = a.index.intersection(b.index)
            if not len(j):
                continue
            df = pd.DataFrame(dict(d=(a[j] - b[j]).values, cl=[cluster_of(i) for i in j]))
            r[f"d_{col}"], r[f"d_{col}_lo"], r[f"d_{col}_hi"] = boot(df, "d", rng); r["n"] = len(j)
        rows.append(r)
    return pd.DataFrame(rows)


def main():
    rng = np.random.default_rng(0)
    FIG.mkdir(parents=True, exist_ok=True)
    meta = json.load(open(MIX / "r5" / "meta.json"))
    panel = select(meta, "sub48"); G = groups_for(panel)
    w = load_wer("r5")
    base = [m for m in ["noisy", "ds_est", "mvdr_online_est", "mvdr_online_dir_est", "mvdr_online_dir_ref", "ref_image"] if m in set(w.method)]
    meths = base + [m for m in PANEL6 if m in set(w.method)]
    T = asr_table(w, G, meths, rng); T.to_csv(R6 / "asr_panel_r5.csv", index=False)
    L = ["# Round 6 summary (generated by `python -m selab.summary_r6`)", "",
         "Real = LibriCSS 7-mic recordings (round-5 items). Panel = 48 items (2 per recording, 24 recordings; 36 overlapped).",
         "CIs: 95% cluster bootstrap over recordings, 2000 resamples. Δ = method minus reference method on the same item. "
         "Holm: within the family of round-6 methods, per group and per comparison (vs unprocessed; vs round-5 DS). "
         "A bootstrap p of 0.000 means < 1/2000.", "",
         "Steering: R5 tracker = round-5 running SRP-PHAT (re-implemented on causal frames); track+hyst. = multi-candidate "
         "tracker, no speaker check; track+ECAPA = with enrolment speaker check; REF dir. = system-identification azimuth "
         "(oracle geometry, upper bound); blind whole-seg. = non-causal segment SRP-PHAT (as round-5 DS).", ""]
    L += ["## Panel, overlapped items (OV10-40)", "", md_asr(T, OV, meths), "", "## Panel, no-overlap items (0S)", "", md_asr(T, S0, meths), ""]
    # per condition, deployable + ref
    L += ["## Panel by overlap condition: Δ word-correct vs unprocessed", "", "| Method | OV10 | OV20 | OV40 |", "|---|---|---|---|"]
    for me in meths:
        cells = []
        for c in ("OV10", "OV20", "OV40"):
            r = T[(T.group == c) & (T.method == me)]
            cells.append(fmt(r.dwc_noisy.iloc[0], r.dwc_noisy_lo.iloc[0], r.dwc_noisy_hi.iloc[0], 2) if len(r) and "dwc_noisy" in r and not pd.isna(r.dwc_noisy.iloc[0]) else "—")
        L.append(f"| {label(me)} | " + " | ".join(cells) + " |")
    L.append("")
    # brittleness
    B = brittleness(w, G[OV], meths); B.to_csv(R6 / "whisper_brittleness_panel.csv", index=False)
    L += ["## Whisper-proxy robustness check (panel, overlapped, n per method below)", "",
          "Catastrophic = word-correct < 0.3 (Whisper transcribed the other talker or stopped early). Median Δ and item counts vs unprocessed.", "",
          "| Method | n | catastrophic | median Δ wc | better / same / worse |", "|---|---|---|---|---|"]
    for _, r in B.iterrows():
        L.append(f"| {r.label} | {r.n} | {r.catastrophic_frac:.2f} | {r.median_d:+.3f} | {r.n_better} / {r.n_same} / {r.n_worse} |")
    L.append("")
    # tracker
    tp = R6 / "tracker_r5.csv"
    if tp.exists():
        tk = pd.read_csv(tp); tk["cl"] = tk.id.map(cluster_of); tk["end10"] = (tk.end_err <= 10).astype(float)
        L += ["## Tracker accuracy (real, all items with a reference: n = 122; 90 overlapped)", "",
              "| Tracker | group | n | mean fraction of 16-ms steps within 10° [95% CI] | end-of-segment within 10° [95% CI] | median end error (°) | within 10° on overlapped steps |",
              "|---|---|---|---|---|---|---|"]
        rows = []
        for mode in ("r5t", "rtn", "rt"):
            for gname, f in ((S0, tk.cond == "0S"), (OV, tk.cond != "0S")):
                s = tk[(tk["mode"] == mode) & f]
                a = boot(s, "frac10", rng); b = boot(s, "end10", rng)
                ovs = s.frac10_overlapped_steps.mean()
                rows.append(dict(mode=mode, group=gname, n=len(s), frac10=a[0], frac10_lo=a[1], frac10_hi=a[2], end10=b[0], end10_lo=b[1], end10_hi=b[2],
                                 median_end=s.end_err.median(), frac10_ovsteps=ovs))
                L.append(f"| {TRK[mode]} | {gname} | {len(s)} | "
                         f"{a[0]:.2f} [{a[1]:.2f}, {a[2]:.2f}] | {b[0]:.2f} [{b[1]:.2f}, {b[2]:.2f}] | {s.end_err.median():.1f} | {ovs:.2f} |")
        pd.DataFrame(rows).to_csv(R6 / "tracker_summary.csv", index=False)
        L += ["", "Round-5 published figures for its causal tracker (its own framing, n = 90 overlapped): 57% end-of-segment within 10°, mean step fraction 0.87 over all 122 items.", ""]
    # objective
    O = obj_table("r5", G[OV], meths, rng)
    if not O.empty:
        O.to_csv(R6 / "objective_panel_r5.csv", index=False)
        L += ["## Objective metrics vs the ESTIMATED reverberant target image (indicative; panel overlapped items)", "",
              "| Method | n | Δ SI-SDR dB [95% CI] | Δ ESTOI [95% CI] |", "|---|---|---|---|"]
        for _, r in O.iterrows():
            if "d_si_sdr" in r and not pd.isna(r.get("d_si_sdr")):
                L.append(f"| {r.label} | {int(r.n)} | {fmt(r.d_si_sdr, r.d_si_sdr_lo, r.d_si_sdr_hi, 2)} | {fmt(r.d_estoi, r.d_estoi_lo, r.d_estoi_hi, 3)} |")
        L.append("")
    # timing
    tsum = R6 / "timing_r6_summary.csv"
    if tsum.exists():
        ts = pd.read_csv(tsum); tj = json.load(open(R6 / "timing_r6.json"))
        L += [f"## Compute (single thread, Python/numpy reference code, 2 vCPU aarch64; {tj['n_items']} overlapped panel items; mean load avg during run {tj['load_mean']:.2f})", "",
              "| Component | algorithmic latency (ms) | hop (ms) | mean per-hop compute (ms) | p99 per-hop (ms) | RTF | of which ECAPA |", "|---|---|---|---|---|---|---|"]
        for _, r in ts.iterrows():
            lat = "n/a (steering only)" if str(r.component).startswith("tracker") else f"{r.algorithmic_latency_ms:.2f}"
            p99 = "" if pd.isna(r.get("p99_ms")) else f"{r.p99_ms:.3f}"
            L.append(f"| {r.component} | {lat} | {r.hop_ms:.0f} | {r.per_hop_ms:.3f} | {p99} | {r.rtf:.3f} | {r.embed_rtf:.3f} |")
        L.append("")
    # held-out
    hc = R6 / "holdout_choice.json"
    if hc.exists():
        ch = json.load(open(hc)); tune = pd.read_csv(R6 / "holdout_tune.csv")
        L += ["## Held-out protocol: tune on sessions 0-2, test on sessions 3-5 (all items)", "",
              f"Selection rule: {ch['rule']}.", "", "Tuning results (sessions 0-2; Δ word-correct vs unprocessed, means):", "",
              "| Config | n OV | Δ OV | n 0S | Δ 0S |", "|---|---|---|---|---|"]
        for _, r in tune.iterrows():
            L.append(f"| {label(r['name'])} | {r.n_ov} | {r.d_ov:+.3f} | {r.n_0s} | {r.d_0s:+.3f} |")
        test = select(meta, "s345"); GT = groups_for(test)
        hm = ["noisy", "ds_est", "ds_td_rt"] + [c["method"] + (f"__{c['suffix']}" if c["suffix"] else "") for c in ch["frozen"] + ch.get("extras", [])]
        hm = [m for m in dict.fromkeys(hm) if m in set(w.method)]
        TT = asr_table(w, GT, hm, rng); TT.to_csv(R6 / "asr_holdout_test.csv", index=False)
        L += ["", f"Frozen: {', '.join(label(c['method'] + ('__' + c['suffix'] if c['suffix'] else '')) for c in ch['frozen'])}. "
              f"Also run with the same parameters: {', '.join(label(c['method'] + ('__' + c['suffix'] if c['suffix'] else '')) for c in ch.get('extras', []))}.", "",
              "### Test sessions 3-5, overlapped", "", md_asr(TT, OV, hm), "", "### Test sessions 3-5, no overlap", "", md_asr(TT, S0, hm), ""]
        # all 144 for the frozen winner
        allm = select(meta, "all"); GA = groups_for(allm)
        TA = asr_table(w, GA, hm, rng); TA.to_csv(R6 / "asr_all144.csv", index=False)
        L += ["### All 144 items (sessions 0-5; sessions 0-2 were the tuning set, so this pooled figure is optimistic)", "",
              md_asr(TA, OV, hm), "", md_asr(TA, S0, hm), ""]
    # sim vs real
    try:
        ws = load_wer("r5sim")
        simm = [m for m in meths if m in set(ws.method) and m != "noisy" and m != "ref_image"]
        SV = sim_vs_real(w, ws, G[OV], simm, rng)
        if not SV.empty:
            SV.to_csv(R6 / "sim_vs_real_r6.csv", index=False)
            from scipy.stats import spearmanr
            rho = spearmanr(SV.d_real, SV.d_sim).correlation if len(SV) > 2 else np.nan
            L += [f"## Sim vs real (panel, overlapped; paired by item). Spearman rank correlation of method effects: {rho:.2f} over {len(SV)} methods", "",
                  "| Method | n | Δ wc real | Δ wc sim | real − sim [95% CI] |", "|---|---|---|---|---|"]
            for _, r in SV.iterrows():
                L.append(f"| {r.label} | {r.n} | {r.d_real:+.3f} | {r.d_sim:+.3f} | {fmt(r['diff'], r.lo, r.hi)} |")
            L.append("")
    except Exception as e:
        L += [f"(sim-vs-real not available: {e!r})", ""]
    (R6 / "summary_r6.md").write_text("\n".join(L))
    # ---- figures
    S = T[T.group == OV].copy()
    S = S[S.method != "noisy"]
    S["lat"] = S.method.map(latency_of)
    fig, ax = plt.subplots(figsize=(8, 0.32 * len(S) + 1.2))
    y = np.arange(len(S))[::-1]
    col = ["#888" if m in BASE else ("#c44" if m.endswith("_ref") else "#269") for m in S.method]
    # one errorbar call per point: errorbar does not accept a list of colours for ecolor
    for yi, (_, r), c in zip(y, S.iterrows(), col):
        ax.errorbar([r.dwc_noisy], [yi], xerr=[[r.dwc_noisy - r.dwc_noisy_lo], [r.dwc_noisy_hi - r.dwc_noisy]],
                    fmt="o", color=c, ecolor=c, capsize=2, ms=4, zorder=3)
    ax.axvline(0, color="k", lw=0.8)
    r5ds = S[S.method == "ds_est"].dwc_noisy
    if len(r5ds):
        ax.axvline(float(r5ds.iloc[0]), color="#888", ls="--", lw=0.8)
    ax.set_yticks(y); ax.set_yticklabels([f"{label(m)}  ({latency_of(m):.1f} ms)" if np.isfinite(latency_of(m)) else f"{label(m)}  (n/a)" for m in S.method], fontsize=7)
    ax.set_xlabel("Δ Whisper word-correct vs unprocessed\n(overlapped panel items, n = 36; 95% cluster-bootstrap CI)", fontsize=8)
    ax.set_title("grey = round-5 baselines, blue = causal (estimated direction),\nred = reference direction; dashed = round-5 DS", fontsize=8)
    fig.tight_layout(); fig.savefig(FIG / "panel_forest_ov.png", dpi=150, bbox_inches="tight"); plt.close(fig)
    D = S[S.method.isin(DEPLOY + ["ds_est", "mvdr_online_est"])]
    fig, ax = plt.subplots(figsize=(6, 4))
    ax.errorbar(D.lat, D.dwc_noisy, yerr=[D.dwc_noisy - D.dwc_noisy_lo, D.dwc_noisy_hi - D.dwc_noisy], fmt="o", capsize=2)
    for _, r in D.iterrows():
        ax.annotate(r.method, (r.lat, r.dwc_noisy), fontsize=6, xytext=(3, 3), textcoords="offset points")
    ax.axhline(0, color="k", lw=0.8); ax.axvline(5, color="r", ls=":", lw=0.8); ax.axvline(10, color="r", ls=":", lw=0.8)
    ax.set_xscale("symlog", linthresh=1); ax.set_xlabel("algorithmic latency (ms)"); ax.set_ylabel("Δ word-correct, overlapped (n = 36)")
    ax.set_title("Latency vs benefit (estimated direction)", fontsize=9)
    fig.tight_layout(); fig.savefig(FIG / "latency_vs_benefit.png", dpi=150); plt.close(fig)
    print("\n".join(L[:60]))


if __name__ == "__main__":
    main()
